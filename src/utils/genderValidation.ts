const MALE_EXCEPTIONS_ENDING_IN_A_YA = new Set([
  'микола', 'ілля', 'микита', 'сава', 'лука', 'хома', 'кузьма', 'данила', 'данило', 'савва',
  'фома', 'кирило', 'микитович', 'михайло'
]);

export function isFemaleName(name: string): boolean {
  if (!name || typeof name !== 'string') return false;
  const cleaned = name.trim().toLowerCase();
  const parts = cleaned.split(/[\s-]+/);
  
  for (const part of parts) {
    if (KNOWN_FEMALE_NAMES.has(part)) return true;
    if (part.endsWith('а') || part.endsWith('я')) {
      if (!MALE_EXCEPTIONS_ENDING_IN_A_YA.has(part)) {
        return true;
      }
    }
  }
  return false;
}

export function checkGenderMismatch(firstName: string, gender: Gender): string | null {
  if (gender === 'male' && isFemaleName(firstName)) {
    return `Увага: Вказано жіноче ім'я ("${firstName}"), але обрано чоловічу стать.`;
  }
  return null;
}
